import json,pickle,sys
sys.path.insert(0,'/workspace/mdz'); import dec
p=pickle.load(open('/workspace/mdz/proj.pkl','rb')); T=p[3]
d=json.load(open('/tmp/props.json'))
keys=[k for k in d if k.split(':')[0] in ('3','4','5','6') or k=='7:1']
def anims(oid): return T[oid][7]
def frames(oid,anim=None):
    for a in T[oid][7]:
        if anim is None or a[0]==anim: return a[7]
    return T[oid][7][0][7]
def ip_off(fr,ip):
    # ip = [0,n] index (0=origin) or [2,name]
    w,h,hx,hy=fr[4],fr[5],fr[7],fr[8]
    if ip[0]==0 and ip[1]==0: return (0.0,0.0)
    pts=fr[9]
    if ip[0]==0: q=pts[ip[1]-1] if ip[1]-1<len(pts) else None
    else: q=next((x for x in pts if x[0]==ip[1]),None)
    if not q: return (0.0,0.0)
    return ((q[1]-hx)*w,(q[2]-hy)*h)
sheets={}  # (oid,anim) -> idx
frows=[]; srows=[]
def sheet(oid,anim):
    k=(oid,anim)
    if k in sheets: return sheets[k]
    fs=frames(oid,anim); first=len(frows)
    for f in fs:
        frows.append('  {"%s", %d, %d, %d, %d, %.4ff, %.4ff},'%(f[0].split('/')[-1].replace('.png',''),f[2],f[3],f[4],f[5],f[7],f[8]))
    sheets[k]=len(srows); srows.append('  {%d, %d}, // %s %s'%(first,len(fs),dec.oname(oid),anim or 'Default'))
    return sheets[k]
def norm(v):
    while isinstance(v,list): v=v[-1]
    return -1 if v is None else v
mains=[]; bases=[]
for k in keys:
    cat,sub=k.split(':'); cat=int(cat)
    if sub.startswith('op'): subv=-12; sub_lt=True
    else: subv=int(sub)
    recs=d[k]
    # group by main spawn
    cur=None
    anim=None
    for r in recs:
        if r['op']=='anim' and cur is not None: cur['anim']=r['v'][1]
    for r in recs:
        if r['op']=='spawn' and r['by']=='map_element':
            cur=dict(cat=cat,sub=subv,iv6=r.get('iv6',-1),oid=r['objid'],name=r['obj'],fmode=0,fconst=0,f_iv3_1=-1,anim=None,bases=[])
            mains.append(cur)
        elif cur is None: continue
        elif r['op']=='anim' and r['on']==cur['name']: cur['anim']=r['v'][1]
        elif r['op']=='frame' and r['on']==cur['name']:
            v=r['v'][1]
            if r.get('iv3')==1: cur['f_iv3_1']=v[1] if v[0]==0 else 0
            elif v[0]==0: cur['fconst']=v[1]; cur['fmode']=0
            elif v[0]==21: cur['fmode']=1 if v[4]==6 else 2
            elif v[0]==19: cur['fmode']=3
        elif r['op']=='spawn' and r['by']==cur['name'] and r['objid'] in (336,339):
            cur['bases'].append(dict(big=1 if r['objid']==339 else 0,frame=0,ip=r['ip'],mframe=norm(r.get('mframe'))))
        elif r['op']=='frame' and r['on'] in ('obst_base','big_obstacle_base') and cur['bases']:
            cur['bases'][-1]['frame']=r['v'][1][1]
out=[]
out.append('// Generated by gen_props.py from data.js create_map_element (categories 3/4/5/6 + 7:1).')
mrows=[]
for m in mains:
    si=sheet(m['oid'],m['anim'])
    fs=frames(m['oid'],m['anim'])
    fb=len(bases)
    for b in m['bases']:
        # base at main image point: offset measured on main frame (mframe or 0)
        mf=fs[b['mframe'] if 0<=b['mframe']<len(fs) else 0]
        ox,oy=ip_off(mf,b['ip'])
        bf=frames(339 if b['big'] else 336)[b['frame']]
        poly=bf[10]; w,h=bf[4],bf[5]
        if not poly:
            hx,hy=bf[7],bf[8]; poly=[-hx,-hy,1-hx,-hy,1-hx,1-hy,-hx,1-hy]  # C2: no polygon = bounding box
        pts=', '.join('%.2ff'%(poly[i]*(w if i%2==0 else h)) for i in range(len(poly)))
        bases.append('  {%d, %d, %d, %.2ff, %.2ff, %d, {%s}},'%(b['mframe'],b['big'],b['frame'],ox,oy,len(poly)//2,pts))
    mrows.append('  {%d, %d, %d, %d, %d, %d, %d, %d, %d}, // %s'%(m['cat'],m['sub'],m['iv6'],si,m['fmode'],m['fconst'],m['f_iv3_1'],fb,len(m['bases']),m['name']))
maxp=max([b.count('f,')+1 for b in bases]) 
open('/workspace/mdz/w/src/world/map_props.inc','w').write('\n'.join(out+[
'static const PropFrame kPropFrames[] = {']+frows+['};',
'static const PropSheet kPropSheets[] = {']+srows+['};',
'static const PropBase kPropBases[] = {']+bases+['};',
'static const PropDef kPropDefs[] = {']+mrows+['};',
'static const int kPropDefCount = %d;'%len(mrows),'']))
print(len(mrows),len(bases),len(frows))
import re
print(max(int(re.search(r'\{[^{]*?, (\d+), \{',b).group(1)) for b in bases))
