#!/usr/bin/env python3
# C2 death animations (Mini DayZ 1.4.1 data.js): the *_dead objects' die1/die2 animations
# (8 fps, no loop; the last frame stays). Usage: extract_die_anims.py proj.pkl out.inc
import pickle, sys
p = pickle.load(open(sys.argv[1], 'rb')); T = p[3]
OBJ = [(210, 'zed_normal_skin1'), (396, 'zed_fast_skin1'), (213, 'zed_army_skin1'),
       (715, 'zed_buried_skin'), (722, 'zed_screamer_skin'), (849, 'zed_tank_skin'),
       (470, 'wolf'), (473, 'deer'), (610, 'rabbit'), (893, 'dog')]
out = ['// Generated by tools/extract_die_anims.py from data.js. Do not edit by hand.']
out.append('static const DieAnim kDieAnims[] = {')
for t, key in OBJ:
    for a in T[t][7]:
        if a[0] not in ('die1', 'die2', 'Default'): continue
        style = 2 if a[0] == 'die2' else 1
        fr = a[7][:6]
        fs = ', '.join('{"%s", %d, %d, %d, %d, %.4ff, %.4ff}' % (f[0].split('/')[-1][:-4], f[2], f[3], f[4], f[5], f[7], f[8]) for f in fr)
        speed = a[1] if a[0] != 'Default' else 0   # tank: Default anim of the dead object, not played
        out.append('  {"%s", %d, %d, %d, {%s}},  // t%d %s' % (key, style, speed, len(fr), fs, t, a[0]))
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
