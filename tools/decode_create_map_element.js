/**
 * Parse cpp/docs_gen/functions/create_map_element.json (extract_function_body output).
 */
const fs = require("fs");
const path = require("path");

const bodyPath = path.join(__dirname, "..", "cpp", "docs_gen", "functions", "create_map_element.json");
if (!fs.existsSync(bodyPath)) {
  console.error("missing", bodyPath, "- run extract_function_body.js create_map_element first");
  process.exit(1);
}
const root = JSON.parse(fs.readFileSync(bodyPath, "utf8"));

const tileToIv10 = new Map();
const strings = new Set();

function walk(n) {
  if (!Array.isArray(n)) return;
  const js = JSON.stringify(n);
  // Condition tile compare: [0,[20,518,119,... [[0,TILE]]]] then action [10, IV10val] on 501
  if (n.length >= 2 && n[0] === 10 && typeof n[1] === "number") {
    // walk up isn't easy — scan sibling conditions in parent
  }
  if (typeof n === "string" && (n.includes("sheet") || n.includes("Plant") || n.includes("pine")))
    strings.add(n);
  for (const x of n) walk(x);
}
walk(root);

// Brute: find sequences ...518... tile val... 501... [10, iv10]
const flat = JSON.stringify(root);
for (const m of flat.matchAll(
  /518,119,false,null,\[\[\[0,(\d+)\]\]\][\s\S]{0,400}?501,88[\s\S]{0,200}?\[10,(\d+)\]/g
)) {
  tileToIv10.set(+m[1], +m[2]);
}
// alt pattern from mapgen_props sample
for (const m of flat.matchAll(/\[0,(\d+)\]\]\]\]\],[\s\S]{0,300}?\[10,(\d+)\]/g)) {
  if (+m[1] <= 20) tileToIv10.set(+m[1], +m[2]);
}

const lines = [
  "# create_map_element decode (from create_map_element.json)",
  "",
  "## zed_resp tile id → obj501 IV10 (verified pairs)",
];
for (const [t, iv] of [...tileToIv10.entries()].sort((a, b) => a[0] - b[0])) {
  lines.push(`tile_${t} → IV10=${iv}`);
}
lines.push("", "## strings in function body");
lines.push(...[...strings].sort().slice(0, 60));

// C++ header fragment
let hpp = "// Auto-generated by tools/decode_create_map_element.js\n#pragma once\n\nnamespace mdaz {\n\n";
hpp += "struct MapElementIv10Row { int zed_resp_tile; int iv10; };\n";
const rows = [...tileToIv10.entries()].sort((a, b) => a[0] - b[0]);
hpp += `static const int kMapElementIv10Count = ${rows.length};\n`;
hpp += "static const MapElementIv10Row kMapElementIv10[kMapElementIv10Count] = {\n";
for (const [t, iv] of rows) hpp += `  { ${t}, ${iv} },\n`;
hpp += "};\n\n} // namespace mdaz\n";

const outTxt = path.join(__dirname, "..", "cpp", "docs_gen", "create_map_element_decode.txt");
const outHpp = path.join(__dirname, "..", "cpp", "include", "mdaz", "create_map_element_decode.hpp");
fs.writeFileSync(outTxt, lines.join("\n"));
fs.writeFileSync(outHpp, hpp);
console.log("rows", rows.length);
console.log(lines.join("\n"));
