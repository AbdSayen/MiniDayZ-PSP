# gen_spawn_drop_inc.py: data.js Function "Spawn_drop" -> cpp/src/world/spawn_drop_count.inc
# Every sub-event "CompareParam(0) = id" whose actions SetInstanceVar IV1 (the C2 array count:
# stack size or item state such as water level / knife condition / charge).
import json, re, sys
s = open(sys.argv[1]).read()
i = s.find('[180,40,null,2,false,false,false,3482364762744142,false,[[1,[2,"Spawn_drop"]]')
st = s.rfind('[0,null,', 0, i)
d = 0; k = st
while True:
    c = s[k]
    if c == '[': d += 1
    elif c == ']':
        d -= 1
        if d == 0: break
    elif c == '"':
        k += 1
        while s[k] != '"':
            if s[k] == '\\': k += 1
            k += 1
    k += 1
ev = json.loads(s[st:k + 1])
rows = []
for x in ev[7]:
    pid = x[5][0][9][2][1][1]
    cnt = None; farmer = 0
    for a in x[6]:
        if a[1] == 88 and a[5][0] == [10, 1]: cnt = a[5][1][1]
    for sub in (x[7] if len(x) > 7 and x[7] else []):
        for a in sub[6]:
            if a[1] == 83 and a[5][0] == [10, 1]: farmer = a[5][1][1][1]
    if cnt is None: continue
    if cnt[0] == 19 and cnt[1] == 80 and cnt[2][0][1] == 95:
        r = (pid, 1, cnt[2][0][2][0][1], cnt[2][0][2][1][1], farmer, [])
    elif cnt[0] == 19 and cnt[1] == 82:
        r = (pid, 2, 0, 0, farmer, [v[1] for v in cnt[2]])
    elif cnt[0] == 0:
        r = (pid, 2, 0, 0, farmer, [cnt[1]])
    else:
        raise SystemExit('rule %r' % (cnt,))
    rows.append(r)
o = ['// Generated by tools/gen_spawn_drop_inc.py from data.js Function "Spawn_drop". DO NOT EDIT.',
     '// kind 1: int(random(a,b)) -> a..b-1; kind 2: choose(list); farmer: perk_farmer AddInstanceVar IV1.',
     '// IV1 = C2 array count: stack size, or item state (bottle/canteen water 0..100, knife condition...).',
     'static const SpawnDropCount kSpawnDropCount[] = {']
for pid, kd, a, b, fa, l in rows:
    o.append('  {%d, %d, %d, %d, %d, %d, {%s}},' % (pid, kd, a, b, fa, len(l), ', '.join(map(str, l or [0]))))
o.append('};')
open(sys.argv[2], 'w').write('\n'.join(o) + '\n')
print(len(rows))
# IV6 (t909 condition): top-level SetInstanceVar IV6 = choose(...) | literal; a sub-event
# "param3 != -1" overrides it with param3 (Spawn_drop caller passes the dropped instance's IV6).
if len(sys.argv) > 3:
    r6 = []
    for x in ev[7]:
        pid = x[5][0][9][2][1][1]
        for a in x[6]:
            if a[1] == 88 and a[5][0] == [10, 6]:
                v = a[5][1][1]
                if v[0] == 19 and v[1] == 82: r6.append((pid, [w[1] for w in v[2]]))
                elif v[0] == 0: r6.append((pid, [v[1]]))
                else: raise SystemExit('iv6 rule %r' % (v,))
    o = ['// Generated by tools/gen_spawn_drop_inc.py from data.js Function "Spawn_drop". DO NOT EDIT.',
         '// t909 IV6 (condition 0..100) rolled at spawn: choose(list); param3 != -1 overrides.',
         'static const SpawnDropIv6 kSpawnDropIv6[] = {']
    for pid, l in r6:
        o.append('  {%d, %d, {%s}},' % (pid, len(l), ', '.join(map(str, l))))
    o.append('};')
    open(sys.argv[3], 'w').write('\n'.join(o) + '\n')
    print(len(r6))
